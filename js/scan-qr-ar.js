// --- PARSE UNITY STUDENT GRADE QR CODE ---
function parseStudentGradeQR(rawText) {
  // Format generated by Unity:
  // "0026271000 | Test Student | Pre:40% | Post:60% | Lessons:1"
  // Optional detailed lesson tokens: "| L:term_01.lesson_01:2/5:3/5"
  const parts = String(rawText || "").split("|").map((p) => p.trim());
  if (parts.length < 3) return null;

  const studentId = parts[0];
  const studentName = parts[1] || "Student";
  let prePct = 0;
  let postPct = 0;
  let lessonsCount = 1;
  const lessonBreakdown = [];

  parts.slice(2).forEach((token) => {
    if (/^Pre:/i.test(token)) {
      prePct = parseInt(token.replace(/[^0-9]/g, ""), 10) || 0;
    } else if (/^Post:/i.test(token)) {
      postPct = parseInt(token.replace(/[^0-9]/g, ""), 10) || 0;
    } else if (/^Lessons:/i.test(token)) {
      lessonsCount = parseInt(token.replace(/[^0-9]/g, ""), 10) || 0;
    } else if (/^L:/i.test(token)) {
      // Example: L:term_01.lesson_01:2/5:3/5
      const segs = token.substring(2).split(":");
      if (segs.length >= 3) {
        const [termId, lessonId] = segs[0].split(".");
        const [preScore, preTotal] = segs[1].split("/").map(Number);
        const [postScore, postTotal] = segs[2].split("/").map(Number);
        if (termId && lessonId) {
          lessonBreakdown.push({
            termId,
            lessonId,
            preScore: preScore || 0,
            preTotal: preTotal || 5,
            postScore: postScore || 0,
            postTotal: postTotal || 5
          });
        }
      }
    }
  });

  return {
    studentId,
    studentName,
    prePct,
    postPct,
    lessonsCount,
    lessonBreakdown
  };
}

function getInitials(name) {
  const parts = String(name || "S").trim().split(/\s+/);
  if (parts.length === 1) return parts[0].substring(0, 2).toUpperCase();
  return (parts[0][0] + parts[parts.length - 1][0]).toUpperCase();
}

// --- SYNC SCANNED STUDENT GRADES TO FIRESTORE & SHOW MODAL ---
async function processScannedQR(decodedText) {
  status.textContent = `QR Detected! Processing...`;

  const parsed = parseStudentGradeQR(decodedText);

  if (!parsed) {
    // Non-grade QR code fallback
    status.textContent = `QR Scanned: ${decodedText}`;
    await saveScanToDatabase(decodedText, "qr");
    return;
  }

  const { studentId, studentName, prePct, postPct, lessonsCount, lessonBreakdown } = parsed;
  const gain = postPct - prePct;
  const gainStr = gain >= 0 ? `+${gain}%` : `${gain}%`;

  // 1. Show Pop-up Modal Immediately for Fast Feedback
  if (modalStudentInitials) modalStudentInitials.textContent = getInitials(studentName);
  if (modalStudentName) modalStudentName.textContent = studentName;
  if (modalStudentId) modalStudentId.textContent = `ID: ${studentId}`;
  if (modalPreScore) modalPreScore.textContent = `${prePct}%`;
  if (modalPostScore) modalPostScore.textContent = `${postPct}%`;
  if (modalGainScore) modalGainScore.textContent = gainStr;
  if (modalSyncText) modalSyncText.textContent = "Syncing grades with database...";
  if (modalLessonsNote) {
    modalLessonsNote.textContent = `Completed Lessons: ${lessonsCount} · Updating records...`;
  }

  if (qrResultModal && !qrResultModal.open) {
    qrResultModal.showModal();
  }

  try {
    // 2. Ensure Student Document Exists & Update Summary Fields in `users/{studentId}`
    const studentRef = doc(db, "users", studentId);
    const studentSnap = await getDoc(studentRef);

    const studentUpdate = {
      schoolId: studentId,
      displayName: studentName,
      fullName: studentName,
      role: "student",
      lastQrSyncAt: serverTimestamp(),
      cachedPreTestAvg: prePct,
      cachedPostTestAvg: postPct
    };

    if (!studentSnap.exists()) {
      studentUpdate.classCode = activeTeacherClassCode;
      studentUpdate.teacherId = activeTeacherId || "";
      studentUpdate.active = true;
      studentUpdate.createdAt = serverTimestamp();
    }

    await setDoc(studentRef, studentUpdate, { merge: true });

    // 3. Check & Update `test_results` so Student Records and Analytics update
    let newlySyncedLessons = 0;

    if (lessonBreakdown.length > 0) {
      // If QR has per-lesson breakdown, write each lesson to Firestore
      for (const item of lessonBreakdown) {
        const lessonRef = doc(db, "users", studentId, "test_results", item.termId, "lessons", item.lessonId);
        await setDoc(lessonRef, {
          lessonId: item.lessonId,
          isPreTestCompleted: true,
          isPostTestCompleted: true,
          preTestScore: item.preScore,
          preTestTotalQuestions: item.preTotal,
          postTestScore: item.postScore,
          postTestTotalQuestions: item.postTotal,
          timestamp: serverTimestamp()
        }, { merge: true });
        newlySyncedLessons++;
      }
    } else if (lessonsCount > 0 && (prePct > 0 || postPct > 0)) {
      // Check if student has any existing lessons in term_01
      const term1LessonsRef = collection(db, "users", studentId, "test_results", "term_01", "lessons");
      const term1Snap = await getDocs(term1LessonsRef);

      const preScoreOutOf10 = Math.round((prePct / 100) * 10);
      const postScoreOutOf10 = Math.round((postPct / 100) * 10);

      if (term1Snap.empty) {
        // Create lesson_01 record from QR averages so Student Records & Analytics reflect it
        await setDoc(doc(db, "users", studentId, "test_results", "term_01", "lessons", "lesson_01"), {
          lessonId: "lesson_01",
          isLessonCompleted: true,
          isPreTestCompleted: true,
          isPostTestCompleted: true,
          preTestScore: preScoreOutOf10,
          preTestTotalQuestions: 10,
          postTestScore: postScoreOutOf10,
          postTestTotalQuestions: 10,
          timestamp: serverTimestamp()
        }, { merge: true });
        newlySyncedLessons = 1;
      } else {
        // Update timestamp on the latest lesson so "Last active" in Student Records updates
        const firstLessonDoc = term1Snap.docs[0];
        await setDoc(doc(db, "users", studentId, "test_results", "term_01", "lessons", firstLessonDoc.id), {
          timestamp: serverTimestamp()
        }, { merge: true });
      }
    }

    // 4. Record in Teacher's Recent Scans
    const scanLabel = `${studentName} (${studentId}) · Pre: ${prePct}% | Post: ${postPct}% (${gainStr})`;
    await saveScanToDatabase(scanLabel, "qr");

    // 5. Update Modal Sync Status
    if (modalSyncText) {
      modalSyncText.textContent = newlySyncedLessons > 0
        ? `Synced ${newlySyncedLessons} new lesson record(s) to database!`
        : `Verified & updated in Student Records & Analytics!`;
    }
    if (modalLessonsNote) {
      modalLessonsNote.textContent = `Completed Lessons: ${lessonsCount} · Learning Gain: ${gainStr}`;
    }
    status.textContent = `Successfully scanned and synced ${studentName}'s grades.`;
  } catch (err) {
    console.error("Error syncing QR grade data:", err);
    if (modalSyncText) {
      modalSyncText.textContent = "Displayed from QR (Offline / Sync warning)";
    }
  }
}

// --- QR CAMERA LOGIC ---
async function stopQrCamera() {
  if (html5QrCode && isCameraOpen) {
    try {
      await html5QrCode.stop();
      html5QrCode.clear();
    } catch (err) {
      console.warn("Error stopping QR scanner:", err);
    }
  }
  isCameraOpen = false;
  qrReaderEl.style.display = "none";
  finderCopy.style.display = "block";
  viewfinder.classList.remove("live");
  camBtn.textContent = "Place Camera / Open Device Camera";
}

camBtn.onclick = async () => {
  if (isCameraOpen) {
    await stopQrCamera();
    status.textContent = "";
    return;
  }

  qrReaderEl.style.display = "block";
  finderCopy.style.display = "none";
  viewfinder.classList.add("live");
  camBtn.textContent = "Stop Camera";
  status.textContent = "Starting camera... Point at a student's Grade QR code.";
  lastScannedCode = "";

  try {
    if (!html5QrCode && window.Html5Qrcode) {
      html5QrCode = new window.Html5Qrcode("qr-reader");
    }

    if (!html5QrCode) {
      status.textContent = "QR scanner library failed to load.";
      return;
    }

    isCameraOpen = true;

    await html5QrCode.start(
      { facingMode: "environment" },
      { fps: 10, qrbox: { width: 220, height: 220 } },
      async (decodedText) => {
        if (decodedText === lastScannedCode) return;
        lastScannedCode = decodedText;

        // Pause/stop camera once scanned so the modal pops up cleanly
        await stopQrCamera();
        await processScannedQR(decodedText);
      },
      () => {
        // Ignore frame-by-frame scan misses
      }
    );
  } catch (err) {
    console.error("Camera error:", err);
    await stopQrCamera();
    status.textContent = "Could not access camera. You can also upload a QR image below.";
  }
};

// --- UPLOAD QR IMAGE FALLBACK (Great for testing on PC!) ---
if (qrFileInput) {
  qrFileInput.addEventListener("change", async (e) => {
    const file = e.target.files?.[0];
    if (!file) return;

    if (isCameraOpen) {
      await stopQrCamera();
    }

    status.textContent = "Reading uploaded QR code image...";
    try {
      if (!html5QrCode && window.Html5Qrcode) {
        html5QrCode = new window.Html5Qrcode("qr-reader");
      }
      const decodedText = await html5QrCode.scanFile(file, true);
      await processScannedQR(decodedText);
    } catch (err) {
      console.error("QR file scan error:", err);
      status.textContent = "Could not detect a valid QR code in that image. Try cropping closer to the QR code.";
    } finally {
      qrFileInput.value = "";
    }
  });
}

// --- FIREBASE RECENT SCANS LOGIC ---
onAuthStateChanged(auth, async (user) => {
  if (!user) {
    window.location.href = "login.html";
    return;
  }

  try {
    const userQ = query(collection(db, "users"), where("uid", "==", user.uid));
    const userSnap = await getDocs(userQ);

    if (!userSnap.empty) {
      activeTeacherId = userSnap.docs[0].id;
    } else {
      const fallbackSnap = await getDocs(query(collection(db, "users"), where("role", "==", "teacher")));
      if (!fallbackSnap.empty) {
        activeTeacherId = fallbackSnap.docs[0].id;
      }
    }

    if (activeTeacherId) {
      // Find teacher's primary classCode in case a new student is scanned
      const classSnap = await getDocs(query(collection(db, "classes"), where("teacherId", "==", activeTeacherId)));
      if (!classSnap.empty) {
        activeTeacherClassCode = classSnap.docs[0].id;
      }
      loadRecentScans();
    }
  } catch (error) {
    console.error("Error loading teacher auth:", error);
  }
});

async function loadRecentScans() {
  if (!activeTeacherId) return;

  try {
    const scansRef = collection(db, "users", activeTeacherId, "recent_scans");
    const scansQuery = query(scansRef, orderBy("timestamp", "desc"), limit(5));
    const scansSnap = await getDocs(scansQuery);

    recentScansList.innerHTML = "";

    if (scansSnap.empty) {
      recentScansList.innerHTML = '<p class="muted center" style="margin-top: 20px;">No recent QR scans found.</p>';
      return;
    }

    scansSnap.forEach((docSnap) => {
      const data = docSnap.data();
      if (data.scanType && data.scanType.toLowerCase() === "ar") return;

      const moduleName = data.moduleName || "Scanned QR Code";

      let timeString = "Recently";
      if (data.timestamp && typeof data.timestamp.toDate === "function") {
        const date = data.timestamp.toDate();
        timeString = date.toLocaleDateString("en-US", {
          month: "short",
          day: "numeric",
          hour: "numeric",
          minute: "2-digit"
        });
      }

      const rowHTML = `
        <div class="scan-row">
          <div>
            <strong>${moduleName}</strong>
            <small>${timeString}</small>
          </div>
          <span class="tag tag-qr">QR</span>
        </div>
      `;
      recentScansList.insertAdjacentHTML("beforeend", rowHTML);
    });

    if (recentScansList.innerHTML.trim() === "") {
      recentScansList.innerHTML = '<p class="muted center" style="margin-top: 20px;">No recent QR scans found.</p>';
    }
  } catch (error) {
    console.error("Error fetching recent scans:", error);
    recentScansList.innerHTML = '<p class="muted center" style="margin-top: 20px;">Could not load recent scans.</p>';
  }
}

export async function saveScanToDatabase(moduleName, type = "qr") {
  if (!activeTeacherId) return;

  try {
    const scansRef = collection(db, "users", activeTeacherId, "recent_scans");
    await addDoc(scansRef, {
      moduleName: moduleName,
      scanType: "qr",
      timestamp: serverTimestamp()
    });

    loadRecentScans();
  } catch (error) {
    console.error("Error saving scan to database:", error);
  }
}

window.saveScanToDatabase = saveScanToDatabase;